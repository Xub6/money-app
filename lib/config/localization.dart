      'restore_from_file': 'ファイルから復元',
    },
  };

  static String getLocaleKey(Locale locale) =>
      '${locale.languageCode}_${locale.countryCode}';

  static String translate(Locale locale, String key) {
    final k = getLocaleKey(locale);
    final map = _strings[k] ?? _strings['zh_TW']!;
    return map[key] ?? _strings['zh_TW']![key] ?? key;
  }

  static String of(BuildContext context, String key) =>
      translate(Localizations.localeOf(context), key);

  static String ofParam(
      BuildContext context, String key, Map<String, dynamic> params) {
    String str = of(context, key);
    params.forEach((k, v) => str = str.replaceAll('{$k}', v.toString()));
    return str;
  }

  static String translateParam(
      Locale locale, String key, Map<String, dynamic> params) {
    String str = translate(locale, key);
    params.forEach((k, v) => str = str.replaceAll('{$k}', v.toString()));
    return str;
  }

  // Maps zh_TW category name (stored in DB) to current locale
  static final Map<String, String> _categoryKeyMap = {
    '餐飲': 'dining', '饮食': 'dining',
    '教育': 'education',
    '娛樂': 'entertainment', '娱乐': 'entertainment',
    '交通': 'transport',
    '購物': 'shopping', '购物': 'shopping',
    '醫療': 'medical', '医疗': 'medical',
    '住居': 'living',
    '其他': 'other',
    '薪資': 'salary', '薪资': 'salary',
    '獎金': 'bonus', '奖金': 'bonus',
    '投資': 'invest_income', '投资': 'invest_income',
    '退款': 'refund',
    '其他收入': 'other_income',
  };

  static String translateCategory(BuildContext context, String storedName) {
    final key = _categoryKeyMap[storedName];
    if (key == null) return storedName;
    return of(context, key);
  }

  static String formatDateForLocale(DateTime date, Locale locale) {
    try {
      Intl.defaultLocale = '${locale.languageCode}_${locale.countryCode}';
      return DateFormat.yMd().format(date);
    } catch (_) {
      return date.toString();
    }
  }
}

class AppLocalizationsDelegate
    extends LocalizationsDelegate<AppLocalizations> {
  const AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => AppLocalizations.supportedLocales
      .any((l) => l.languageCode == locale.languageCode);

  @override
  Future<AppLocalizations> load(Locale locale) async =>
      AppLocalizations();

  @override
  bool shouldReload(covariant LocalizationsDelegate<AppLocalizations> old) =>
      false;
}
